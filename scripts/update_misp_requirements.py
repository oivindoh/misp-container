#!/usr/bin/env python3
"""Resolve the Python packages of both images into hash-locked files.

Usage: update_misp_requirements.py

Writes three files, each a closure pinned with uv for the Python version the
image installs, on every platform, with the hash of every file of each pin:
files/requirements-misp.txt from MISP's requirements.txt at the Dockerfile's
CORE_COMMIT, or else its CORE_TAG; files/requirements-final.txt from
files/requirements-final.in, within the first; files/requirements-modules.txt
from files/requirements-modules.in. The images install exactly these pins and
refuse a file whose hash differs, so run this on every MISP bump and after a
change to an .in file.
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DOCKERFILE = REPO / "Dockerfile"
TARGET = REPO / "files/requirements-misp.txt"
# (source, target): the image's own packages, resolved within MISP's
LOCKS = [(REPO / "files/requirements-final.in", REPO / "files/requirements-final.txt"),
         (REPO / "files/requirements-modules.in", REPO / "files/requirements-modules.txt")]
RAW = "https://raw.githubusercontent.com/MISP/MISP/{ref}/requirements.txt"


def misp_ref(dockerfile: str) -> str:
    """The MISP commit the Dockerfile pins, or else its tag."""
    commit = re.search(r"^ARG CORE_COMMIT=(\S+)", dockerfile, re.M)
    tag = re.search(r"^ARG CORE_TAG=(\S+)", dockerfile, re.M)
    if not (commit or tag):
        raise SystemExit("the Dockerfile pins no CORE_COMMIT and no CORE_TAG")
    return (commit or tag).group(1)


def python_version(dockerfile: str) -> str:
    """The Python version of the image: the libpython stdlib package the final stage installs."""
    found = re.search(r"\blibpython(3\.\d+)-stdlib\b", dockerfile)
    if not found:
        raise SystemExit("the Dockerfile installs no libpython3.N-stdlib: find the image's Python version")
    return found.group(1)


def compile_lock(source: Path, target: Path, python: str, header: str, constraint: Path | None = None) -> None:
    """target: the closure of source, every pin with its hashes, under header."""
    subprocess.run(["uv", "pip", "compile", str(source), "--universal", "--generate-hashes", "--quiet",
                    "--python-version", python, "--no-header", "--no-annotate",
                    *(["-c", str(constraint)] if constraint else []), "-o", str(target)], check=True)
    target.write_text(header + target.read_text())


def main() -> int:
    if len(sys.argv) > 1:
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return 2
    dockerfile = DOCKERFILE.read_text()
    ref = misp_ref(dockerfile)
    python = python_version(dockerfile)
    with urllib.request.urlopen(RAW.format(ref=ref), timeout=60) as resp:
        requirements = resp.read().decode()
    with tempfile.TemporaryDirectory() as tmp:
        source = Path(tmp, "requirements.txt")
        source.write_text(requirements)
        compile_lock(source, TARGET, python,
                     f"# The packages MISP's own scripts import, resolved from MISP's requirements.txt at {ref}.\n"
                     "# Generated by mise run misp-requirements: do not edit by hand.\n")
    for source, target in LOCKS:
        compile_lock(source, target, python,
                     f"# Resolved from {source.name}. Generated by mise run misp-requirements: do not edit by hand.\n",
                     constraint=TARGET if target.name == "requirements-final.txt" else None)
    print(f"wrote {TARGET.relative_to(REPO)} for MISP {ref}, and {', '.join(t.name for _, t in LOCKS)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
